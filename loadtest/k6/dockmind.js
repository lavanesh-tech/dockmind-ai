// Load test for DockMind, run against the whole local system through the API gateway.
//   ./scripts/run-local.sh load
// It signs in through Keycloak (smoke-test client), prepares docks and shipments, then sends a
// steady mix of reads and bookings. Results (p50/p95/p99 etc.) are written to docs/benchmarks/load/.
import http from 'k6/http';
import { check } from 'k6';

const GATEWAY = __ENV.GATEWAY_URL || 'http://api-gateway:8080';
const KEYCLOAK = __ENV.KEYCLOAK_URL || 'http://keycloak:8080';
const RATE = Number(__ENV.RATE || 15);          // requests per second (below the gateway's per-tenant limit)
const DURATION = __ENV.DURATION || '2m';
const DAY = new Date(Date.now() + 3 * 86400000).toISOString().slice(0, 10);

export const options = {
  scenarios: {
    mixed: { executor: 'constant-arrival-rate', rate: RATE, timeUnit: '1s', duration: DURATION,
             preAllocatedVUs: 20, maxVUs: 50 },
  },
  thresholds: {
    http_req_failed: ['rate<0.01'],
    'http_req_duration{kind:read}': ['p(95)<500'],
    'http_req_duration{kind:write}': ['p(95)<1000'],
  },
  summaryTrendStats: ['avg', 'min', 'med', 'p(90)', 'p(95)', 'p(99)', 'max'],
};

function token(username) {
  const res = http.post(`${KEYCLOAK}/realms/dockmind/protocol/openid-connect/token`, {
    grant_type: 'password', client_id: 'dockmind-smoke', client_secret: __ENV.SMOKE_SECRET,
    username, password: __ENV.DEMO_USER_PASSWORD,
  });
  if (res.status !== 200) {
    throw new Error(`Login failed for ${username}: ${res.status} ${res.body}`);
  }
  return res.json('access_token');
}

const json = (t) => ({ headers: { Authorization: `Bearer ${t}`, 'Content-Type': 'application/json' } });

export function setup() {
  const admin = token('admin.acme');
  const dispatcher = token('dispatcher.acme');
  const run = Date.now().toString(36).toUpperCase();
  for (const code of [`L${run}A`, `L${run}B`]) {
    http.post(`${GATEWAY}/api/v1/docks`, JSON.stringify({ code, capabilities: [], opensAt: '06:00', closesAt: '22:00' }), json(admin));
  }
  for (let i = 0; i < 20; i++) {
    http.post(`${GATEWAY}/api/v1/shipments`, JSON.stringify({
      reference: `LOAD-${run}-${i}`, direction: 'INBOUND', palletCount: 10 + i, requiredCapabilities: [],
      priority: i % 5 === 0 ? 'EXPEDITED' : 'STANDARD',
      windowStart: `${DAY}T08:00:00Z`, windowEnd: `${DAY}T12:00:00Z`,
    }), json(dispatcher));
  }
  http.post(`${GATEWAY}/api/v1/schedules/${DAY}/compute`, JSON.stringify({ crewCapacity: 2 }), json(dispatcher));
  return { dispatcher, run };
}

export default function (data) {
  // Access tokens live 5 minutes; keep DURATION under that (default 2m).
  const p = json(data.dispatcher);
  const roll = Math.random();
  let res;
  if (roll < 0.35) {
    res = http.get(`${GATEWAY}/api/v1/schedules/${DAY}`, Object.assign({ tags: { kind: 'read', name: 'GET schedule' } }, p));
  } else if (roll < 0.6) {
    res = http.get(`${GATEWAY}/api/v1/shipments?from=${DAY}T00:00:00Z&to=${DAY}T23:59:00Z`,
      Object.assign({ tags: { kind: 'read', name: 'GET shipments' } }, p));
  } else if (roll < 0.85) {
    res = http.get(`${GATEWAY}/api/v1/docks`, Object.assign({ tags: { kind: 'read', name: 'GET docks' } }, p));
  } else {
    res = http.post(`${GATEWAY}/api/v1/shipments`, JSON.stringify({
      reference: `LOAD-${data.run}-${__VU}-${__ITER}`, direction: 'OUTBOUND', palletCount: 12, requiredCapabilities: [],
      priority: 'STANDARD', windowStart: `${DAY}T13:00:00Z`, windowEnd: `${DAY}T16:00:00Z`,
    }), Object.assign({ tags: { kind: 'write', name: 'POST shipment' } }, p));
  }
  check(res, { 'status is 2xx': (r) => r.status >= 200 && r.status < 300 });
}

function ms(v) {
  return v === undefined ? 'n/a' : `${v.toFixed(1)} ms`;
}

export function handleSummary(data) {
  const row = (label, m) => m
    ? `| ${label} | ${ms(m.values.med)} | ${ms(m.values['p(95)'])} | ${ms(m.values['p(99)'])} | ${ms(m.values.max)} |`
    : `| ${label} | | | | |`;
  const failed = data.metrics.http_req_failed ? (data.metrics.http_req_failed.values.rate * 100).toFixed(2) : 'n/a';
  const md = `# Load test results

_Generated by \`loadtest/k6/dockmind.js\` on ${new Date().toISOString()}. Measured on the developer's Mac
with every service, database, Kafka and Keycloak running locally in Docker. Not a production benchmark._

Load: ${RATE} requests/s for ${DURATION} (${data.metrics.http_reqs ? data.metrics.http_reqs.values.count : '?'} requests in total), through the API gateway (JWT checked at the edge and in each service).

| Requests | p50 | p95 | p99 | Max |
|---|---|---|---|---|
${row('All', data.metrics.http_req_duration)}
${row('Reads', data.metrics['http_req_duration{kind:read}'])}
${row('Bookings (writes)', data.metrics['http_req_duration{kind:write}'])}

Failed requests: ${failed}%. Thresholds: ${Object.entries(data.metrics).filter(([, m]) => m.thresholds)
    .map(([n, m]) => `${n} ${Object.values(m.thresholds).every((t) => t.ok) ? 'passed' : 'FAILED'}`).join('; ')}.
`;
  return {
    stdout: md,
    '/results/RESULTS.md': md,
    '/results/summary.json': JSON.stringify(data, null, 2),
  };
}
